test("MAIN metrics bundle matches its canonical inputs and does not reuse isolated dependency filenames", () => {
  const read = name => fs.readFileSync(path.join(__dirname, "../extension", name), "utf8").replace(/\r\n/g, "\n");
  assert.equal(read("json-capture-metrics-main.js"), "// Generated by scripts/build-json-capture-metrics.js; edit the canonical inputs.\n"
    + ["transfer-diagnostics.js", "json-capture-metrics.js"].map(read).join("\n"));
  const manifest = JSON.parse(read("manifest.json"));
  const mainFiles = new Set(manifest.content_scripts.filter(entry => entry.world === "MAIN").flatMap(entry => entry.js));
  assert.ok(mainFiles.has("json-capture-metrics-main.js"));
  for (const entry of manifest.content_scripts.filter(entry => entry.world !== "MAIN"))
    for (const file of entry.js) assert.equal(mainFiles.has(file), false);
});

test("every relay uses the same diagnostic contract and rejects private data at every depth", async () => {
  const canonical = fs.readFileSync(path.join(__dirname, "../extension/transfer-diagnostics.js"), "utf8").replace(/\r\n/g, "\n");
  assert.equal(fs.readFileSync(path.join(__dirname, "../supabase/functions/_shared/transfer-diagnostics.js"), "utf8").replace(/\r\n/g, "\n"), canonical);
  const edge = await import("../supabase/functions/transfer-telemetry/validation.mjs");
  const safe = { version: 1, error_code: "paste_not_retained", error_origin: "destination", paste_populated: true, paste_stable: false,
    summary_chars: 1400, summary_bytes: 1500, paste_attempts: 3, prepared_diagnostics: { version: 1, error_code: "editor_has_draft" },
    paste_events: [{ event: "paste_verify", at_ms: 100 }, { event: "failure", at_ms: 650, code: "paste_not_retained" }] };
  assert.deepEqual(edge.validateTelemetryPayload(payload({ diagnostics: safe })), validateTelemetryPayload(payload({ diagnostics: safe })));
  for (const invalid of [{ ...safe, raw_error: "PRIVATE" }, { ...safe, error_code: "PRIVATE" },
    { ...safe, summary_chars: -1 }, { ...safe, summary_chars: 1.2 }, { ...safe, online: "PRIVATE" },
    { ...safe, paste_events: [{ event: "failure", at_ms: 0, text: "PRIVATE" }] },
    { ...safe, prepared_diagnostics: { version: 1, stack: "PRIVATE" } },
    { ...safe, prepared_diagnostics: { version: 1, prepared_diagnostics: { version: 1 } } }]) {
    assert.equal(validateTelemetryPayload(payload({ diagnostics: invalid })), null);
    assert.equal(edge.validateTelemetryPayload(payload({ diagnostics: invalid })), null);
  }
  assert.ok(validateTelemetryPayload(payload()), "Old clients retain the metadata API.");
});

test("attachment decoding clues survive both relays while private or arbitrary values are rejected", async () => {
  const edge = await import("../supabase/functions/transfer-telemetry/validation.mjs");
  const attempt = { mode: "fresh", outcome: "failed", failure_check: "invalid_utf8", failure_stage: "attachment_body",
    failure_decode_stage: "chunk", failure_file_extension: "csv", failure_response_charset: "missing", failure_body_hint: "unrecognized" };
  const report = changes => ({ version: 1, capture_detail: "invalid_utf8", json_attempts: [{ ...attempt, ...changes }] });
  for (const key of ["failure_file_extension", "failure_response_charset", "failure_body_hint", "failure_decode_stage"]) {
    for (const value of [...diagnostics.jsonAttemptSchema[key].values, "PRIVATE_FILE.csv", "https://PRIVATE", null]) {
      const data = payload({ diagnostics: report({ [key]: value }) });
      const valid = diagnostics.jsonAttemptSchema[key].values.includes(value);
      assert.equal(Boolean(validateTelemetryPayload(data)), valid);
      assert.equal(Boolean(edge.validateTelemetryPayload(data)), valid);
    }
  }
  for (const key of ["file_name", "file_id", "url", "prefix", "bytes", "content", "raw_error"])
    assert.equal(validateTelemetryPayload(payload({ diagnostics: report({ [key]: "PRIVATE" }) })), null);
});

