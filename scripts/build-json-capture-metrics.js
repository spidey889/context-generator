const fs = require("node:fs");
const path = require("node:path");
const directory = path.join(__dirname, "../extension");
// Keep MAIN's dependency filename distinct from the isolated registrations.
// Brave demonstrated a present bridge with a missing shared helper when the
// same dependency filenames were reused across those worlds at document_start.
const inputs = ["transfer-diagnostics.js", "json-capture-metrics.js"];
const output = "// Generated by scripts/build-json-capture-metrics.js; edit the canonical inputs.\n"
  + inputs.map(file => fs.readFileSync(path.join(directory, file), "utf8").replace(/\r\n/g, "\n")).join("\n");
fs.writeFileSync(path.join(directory, "json-capture-metrics-main.js"), output);
